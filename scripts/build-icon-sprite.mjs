import { existsSync, readFileSync, writeFileSync } from "node:fs";

const lucide = new URL("./", import.meta.resolve("lucide-static/package.json"));
const output = new URL("../app/public/images/", import.meta.url);
const icons = {
    arrow: "arrow-right",
    attention: "circle-alert",
    bell: "bell",
    chat: "message-circle",
    check: "check",
    "chevron-left": "chevron-left",
    "chevron-right": "chevron-right",
    close: "x",
    code: "code-xml",
    cube: "box",
    database: "database",
    down: "chevron-down",
    "ellipsis-vertical": "ellipsis-vertical",
    expand: "maximize-2",
    file: "file-text",
    folder: "folder",
    grid: "layout-grid",
    help: "circle-help",
    menu: "menu",
    "no-access": "ban",
    paperclip: "paperclip",
    play: "play",
    plug: "plug",
    plus: "plus",
    puzzle: "puzzle",
    robot: "bot",
    send: "send-horizontal",
    settings: "settings",
    setup: "sliders-horizontal",
    slash: "slash",
    star: "star",
    stop: "square",
    workflow: "workflow",
};

const symbols = Object.entries(icons).map(([id, name]) => {
    const source = readFileSync(new URL(`icons/${name}.svg`, lucide), "utf8");
    const svg = source.match(
        /<svg\b[^>]*\bviewBox="([^"]+)"[^>]*>([\s\S]*?)<\/svg>\s*$/,
    );
    if (!svg)
        throw new Error(`Lucide icon ${name} has no SVG root with a viewBox.`);
    return `<symbol id="${id}" viewBox="${svg[1]}">${svg[2]}</symbol>`;
});

writeIfChanged(
    "workspace-icons.svg",
    `<!-- Generated by scripts/build-icon-sprite.mjs. Do not edit directly.
Lucide icons. Licence: lucide-LICENSE.txt. -->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols.join("\n")}
</svg>
`,
);
writeIfChanged(
    "lucide-LICENSE.txt",
    readFileSync(new URL("LICENSE", lucide), "utf8"),
);

function writeIfChanged(name, content) {
    const path = new URL(name, output);
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
        writeFileSync(path, content);
    }
}
